def animate_print(text, char_delay=0, line_delay=0.0000000000, enabled=True):
  """动画打印：默认逐字符打印每行（可通过 `--no-anim` 关闭）。

  - `char_delay`: 每字符延迟（秒）
  - `line_delay`: 每行结束后的额外延迟（秒）
  - `enabled`: False 时直接一次性打印完整文本
  """
  if not enabled:
    print(text)
    return

  import time, sys

  for i, line in enumerate(text.splitlines()):
    for ch in line:
      sys.stdout.write(ch)
      sys.stdout.flush()
      time.sleep(char_delay)
    # 换行
    sys.stdout.write("\n")
    sys.stdout.flush()
    # 每行间稍作停顿
    time.sleep(line_delay)
